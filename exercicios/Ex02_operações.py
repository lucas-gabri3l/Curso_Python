numero1 = int(input("Digite o primeiro número: "))
numero2 = int(input("Digite o segundo número: "))
soma = numero1 + numero2
subtracao = numero1 - numero2
divisao = numero1 / numero2
multiplicacao = numero1 * numero2
print(f"A soma do número {numero1} + {numero2} é {soma}")
print(f"A subtração do número {numero1} - {numero2} é {subtracao}")
print(f"A divisão do número {numero1} por {numero2} é {divisao}")
print(f"A multiplicação do número {numero1} x {numero2} é {multiplicacao}")